// DUML 协议自测：拿 langhua98/Linggo 仓库 ble.html 里的 JS（OM6 上实测过）算出来的帧逐字节核对 Duml.swift。
// 后两条（回中、yaw -90°）和 ble.html 自己的自检用的是同一对已知帧。
// 编 App 之前在 Mac 上跑（.github/workflows/build.yml）：swiftc App/Duml.swift Tests/main.swift -o dumlcheck && ./dumlcheck
// 这个文件由 ble.html 的 JS 生成标准答案，改 Duml.swift 时别改这里的数。
import Foundation

var failed = 0
func check(_ name: String, _ ok: Bool, _ detail: @autoclosure () -> String = "") {
    if ok { print("通过  \(name)") } else { failed += 1; print("不对  \(name)  \(detail())") }
}
func hex(_ b: [UInt8]) -> String { b.map { String(format: "%02x", $0) }.joined(separator: " ") }

// CRC 初值（ble.html 自检同款）
check("CRC8 初值 0x77", Duml.crc8([0x55, 0x15, 0x04]) == 0xa9)
check("CRC16 初值 0x3692", Duml.crc16([0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0x01, 0x00, 0x00, 0x04, 0x14,
                                      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05, 0x0f]) == 0x65ab)

// 整帧
let frames: [(String, [UInt8], [UInt8])] = [
    ("version", Duml.frame(seq: 0xA001, flags: 0x40, cmdSet: 0x00, cmdId: 0x01),
     [0x55, 0x0d, 0x04, 0x33, 0x02, 0x04, 0x01, 0xa0, 0x40, 0x00, 0x01, 0x73, 0x5d]),
    ("yaw+100", Duml.frame(seq: 0xC001, flags: 0x40, cmdSet: 0x04, cmdId: 0x0c, payload: Duml.speed(yaw: 100, pitch: 0)),
     [0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0x01, 0xc0, 0x40, 0x04, 0x0c, 0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x0f, 0xfb, 0xe6]),
    ("pitch-250", Duml.frame(seq: 0xC002, flags: 0x40, cmdSet: 0x04, cmdId: 0x0c, payload: Duml.speed(yaw: 0, pitch: -250)),
     [0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0x02, 0xc0, 0x40, 0x04, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x06, 0xff, 0x80, 0x0f, 0xba, 0xa0]),
    ("stop", Duml.frame(seq: 0xC0ff, flags: 0x40, cmdSet: 0x04, cmdId: 0x0c, payload: Duml.stop),
     [0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0xff, 0xc0, 0x40, 0x04, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x01, 0x5f, 0xb0]),
    ("center-abs", Duml.frame(seq: 1, cmdSet: 0x04, cmdId: 0x14, payload: [0, 0, 0, 0, 0, 0, 0x05, 15]),
     [0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0x01, 0x00, 0x00, 0x04, 0x14, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05, 0x0f, 0xab, 0x65]),
    ("yaw-90-abs", Duml.frame(seq: 1, cmdSet: 0x04, cmdId: 0x14, payload: Duml.i16(-900) + [0, 0, 0, 0, 0x05, 15]),
     [0x55, 0x15, 0x04, 0xa9, 0x02, 0x04, 0x01, 0x00, 0x00, 0x04, 0x14, 0x7c, 0xfc, 0x00, 0x00, 0x00, 0x00, 0x05, 0x0f, 0x7b, 0xf0]),
]
for (name, got, want) in frames { check("帧 " + name, got == want, "得到 \(hex(got))，应为 \(hex(want))") }

// 拆帧：全部帧连在一起、前面加几个噪声字节、按 20 字节一包分着来（和蓝牙通知一样）
var all: [UInt8] = [0x00, 0x13, 0x55]
for (_, _, want) in frames { all += want }
let attFrames: [[UInt8]] = [
    [0x55, 0x35, 0x04, 0x68, 0x02, 0x04, 0x07, 0x00, 0x00, 0x04, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xd8, 0xa6, 0x2b, 0x3f, 0x2e, 0xc7, 0x30, 0xbf, 0x3a, 0x23, 0xf7, 0xbd, 0xa1, 0xbc, 0x78, 0x3e, 0x99, 0x17],
    [0x55, 0x35, 0x04, 0x68, 0x02, 0x04, 0x07, 0x00, 0x00, 0x04, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xb8, 0x3a, 0xff, 0x3e, 0x40, 0xda, 0x03, 0xbe, 0xdb, 0xd5, 0xfd, 0xbd, 0x32, 0x28, 0x59, 0xbf, 0xa5, 0xca],
    [0x55, 0x35, 0x04, 0x68, 0x02, 0x04, 0x07, 0x00, 0x00, 0x04, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xc9, 0xa5],
]
for f in attFrames { all += f }
var parser = Duml.Parser()
var got: [Duml.Frame] = []
var i = 0
while i < all.count { got += parser.push(Array(all[i..<min(i + 20, all.count)])); i += 20 }
check("拆帧个数", got.count == frames.count + attFrames.count, "拆出 \(got.count) 帧")
if got.count == frames.count + attFrames.count {
    check("拆帧内容", got[1].cmdSet == 0x04 && got[1].cmdId == 0x0c && got[1].seq == 0xC001 && got[1].payload == Duml.speed(yaw: 100, pitch: 0))
}

// 姿态：四元数 → 欧拉角、重力方向（和 ble.html 的 decodeQuat / quatToEuler / gravityBody 比）
struct Want { let yaw: Double, pitch: Double, roll: Double, g: [Double] }
let wants: [Want] = [
    Want(yaw: 29.99999934506699, pitch: 9.999999114103167, roll: -88.9999960419215, g: [0.17364816244001346, 0.9846577447620732, -0.017187332909255115]),
    Want(yaw: -120.00000073389988, pitch: -19.999999949563495, roll: 4.999999982739703, g: [-0.34202014249847323, -0.08189960811404795, -0.9361168075672212]),
    Want(yaw: 0, pitch: 0, roll: 0, g: [0.0, 0.0, -1.0]),
]
for (k, f) in attFrames.enumerated() {
    var p = Duml.Parser()
    guard let fr = p.push(f).first, let a = Duml.attitude(fr.payload) else { check("姿态 \(k)", false, "解不出来"); continue }
    let w = wants[k]
    let ok = abs(a.yaw - w.yaw) < 1e-3 && abs(a.pitch - w.pitch) < 1e-3 && abs(a.roll - w.roll) < 1e-3
        && zip(a.gravity, w.g).allSatisfy { abs($0 - $1) < 1e-5 }
    check("姿态 \(k)", ok, "得到 \(a.yaw) \(a.pitch) \(a.roll) \(a.gravity)")
}
// OM6 那样装（横滚 -89°）时能算出仰角
var pe = Duml.Parser()
check("仰角", abs((pe.push(attFrames[0]).first.flatMap { Duml.attitude($0.payload) }?.elevation ?? 99) - 10) < 0.5)
check("折角度", Duml.wrap(190) == -170 && Duml.wrap(-190) == 170 && Duml.wrap(30) == 30)

if failed > 0 { print("有 \(failed) 项不对：协议层有问题，不能往云台发帧"); exit(1) }
print("DUML 自测全部通过")

